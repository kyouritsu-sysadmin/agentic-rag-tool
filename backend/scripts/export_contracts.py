"""Generate TypeScript wire contracts from FastAPI's OpenAPI schemas.

Run with .venv/bin/python backend/scripts/export_contracts.py [--check].
Requires no database, credentials, network, or model loading.
"""

import argparse
import json
from pathlib import Path
from kyoritsu_backend.main import create_app

TARGET = Path(__file__).resolve().parents[2] / "frontend/src/lib/contracts/api.ts"


def typescript(schema):
    if "$ref" in schema:
        return schema["$ref"].rsplit("/", 1)[-1]
    if "enum" in schema:
        return " | ".join(json.dumps(v, ensure_ascii=False) for v in schema["enum"])
    if "const" in schema:
        return json.dumps(schema["const"], ensure_ascii=False)
    for keyword, separator in [("anyOf", " | "), ("oneOf", " | "), ("allOf", " & ")]:
        if keyword in schema:
            return separator.join(typescript(s) for s in schema[keyword])
    kind = schema.get("type")
    if isinstance(kind, list):
        return " | ".join(typescript({**schema, "type": k}) for k in kind)
    if kind == "array":
        return f"Array<{typescript(schema['items'])}>"
    if kind == "object" or "properties" in schema:
        properties = schema.get("properties", {})
        if not properties:
            extra = schema.get("additionalProperties", {})
            return f"Record<string, {typescript(extra) if isinstance(extra, dict) else 'unknown'}>"
        required = schema.get("required", [])
        fields = [
            f"  {json.dumps(name)}{'' if name in required else '?'}: {typescript(value)};"
            for name, value in properties.items()
        ]
        return "{\n" + "\n".join(fields) + "\n}"
    return {
        "string": "string",
        "integer": "number",
        "number": "number",
        "boolean": "boolean",
        "null": "null",
    }.get(kind, "unknown")


def render():
    schemas = create_app().openapi()["components"]["schemas"]
    return (
        "// Generated by backend/scripts/export_contracts.py. Do not edit by hand.\n"
        "// Dates are ISO strings on the wire; feature view models normalize them.\n\n"
        + "\n\n".join(
            f"export type {name} = {typescript(schema)};"
            for name, schema in sorted(schemas.items())
        )
        + "\n"
    )


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = render()
    if args.check:
        if not TARGET.exists() or TARGET.read_text() != expected:
            raise SystemExit(
                "Frontend API contracts are stale; run backend/scripts/export_contracts.py"
            )
        print("Frontend API contracts match backend OpenAPI")
    else:
        TARGET.parent.mkdir(parents=True, exist_ok=True)
        TARGET.write_text(expected)
        print(f"Generated {TARGET}")


if __name__ == "__main__":
    main()
